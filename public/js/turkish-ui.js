    document.addEventListener('invalid', function (event) {
        var field = event.target, validity = field.validity;
        if (!validity || validity.customError) return;
        var message = 'Lütfen geçerli bir değer girin.';
        if (validity.valueMissing) message = 'Lütfen bu alanı doldurun.';
        else if (validity.typeMismatch && field.type === 'email') message = 'Geçerli bir e-posta adresi girin.';
        else if (validity.rangeUnderflow) message = 'Değer en az ' + field.min + ' olmalıdır.';
        else if (validity.rangeOverflow) message = 'Değer en fazla ' + field.max + ' olabilir.';
        else if (validity.tooShort) message = 'En az ' + field.minLength + ' karakter girin.';
        else if (validity.tooLong) message = 'En fazla ' + field.maxLength + ' karakter girin.';
        else if (validity.badInput || validity.stepMismatch) message = 'Geçerli bir sayı girin.';
        field.setCustomValidity(message);
        field.dataset.turkishValidity = '1';
    }, true);
    function clearValidation(event) {
        if (event.target.dataset.turkishValidity) {
            event.target.setCustomValidity('');
            delete event.target.dataset.turkishValidity;
        }
    }
